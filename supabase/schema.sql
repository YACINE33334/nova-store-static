-- nova_admin: no policies → only the security-definer helper / superuser can read it.

-- ---------- Supabase Storage bucket: product-images ----------
-- Public read (storefront images) + admin-only upload/delete.
DO $$
DECLARE
  bid TEXT;
BEGIN
  SELECT id INTO bid FROM storage.buckets WHERE name = 'product-images';
  IF bid IS NULL THEN
    INSERT INTO storage.buckets (id, name, public) VALUES ('product-images', 'product-images', true);
  ELSE
    UPDATE storage.buckets SET public = true WHERE id = bid;
  END IF;
END
$$;

DROP POLICY IF EXISTS "nova images public read" ON storage.objects;
CREATE POLICY "nova images public read" ON storage.objects
  FOR SELECT USING (bucket_id = 'product-images');

DROP POLICY IF EXISTS "nova images admin insert" ON storage.objects;
CREATE POLICY "nova images admin insert" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'product-images' AND public.is_nova_admin());

DROP POLICY IF EXISTS "nova images admin update" ON storage.objects;
CREATE POLICY "nova images admin update" ON storage.objects
  FOR UPDATE TO authenticated
  USING (bucket_id = 'product-images' AND public.is_nova_admin())
  WITH CHECK (bucket_id = 'product-images' AND public.is_nova_admin());

DROP POLICY IF EXISTS "nova images admin delete" ON storage.objects;
CREATE POLICY "nova images admin delete" ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'product-images' AND public.is_nova_admin());